return function(test,equal)
 local G=require('src.game');local C=require('src.idea_companions');local V=require('src.visibility');local P=require('src.persistence')
 local function trial()
  local s=G.new(37,nil,{class_id=C.spirit_id});local p=G.player(s);p.position.x,p.position.y=7,6;V.recompute(s)
  return s,p
 end
 test('Spiritbinder paid placement is pure in preview and creates only one nonblocking friendly object',function()
  local s,p=trial();local before=G.snapshot(s);local rng=s.rng.state
  for _=1,20 do assert(G.preview(s,'sweeping_slash',1,0).valid)end;equal(before,G.snapshot(s))
  assert(G.submit(s,{kind='sweeping_slash',dx=1,dy=0}));local e=assert(C.owned(s,'spirit'))
  assert(e.position.x==9 and e.position.y==6 and e.owner_id==p.id and not e.hp and not e.blocks_movement)
  assert(s.clock==140 and s.rng.state==rng and not e.ai_id and not e.pending_attack)
  assert(G.restore(G.snapshot(s)))
 end)
 test('a familiar attacks only on a paid visible adjacent command and never on waits',function()
  local s,p=trial();assert(G.submit(s,{kind='sweeping_slash',dx=1,dy=0}))
  local e=G.spawn_enemy(s,'core:enemy/mossbound_guard',10,6,100000)
  for _=1,3 do assert(G.submit(s,{kind='wait'}))end;assert(e.hp==10)
  local before=s.clock;local _,_,events=G.submit(s,{kind='sweeping_slash',dx=1,dy=0})
  assert(e.hp==8 and s.clock==before+140)
  local hits=0;for _,v in ipairs(events)do if v.kind=='AttackPerformed'then assert(v.source_id==p.id and v.from_x==9);hits=hits+1 end end
  assert(hits==1)
 end)
 test('repositioning preserves the single familiar ID and cannot scout or cross a wall',function()
  local s,p=trial();assert(G.submit(s,{kind='sweeping_slash',dx=1,dy=0}));local e=C.owned(s,'spirit')
  assert(G.submit(s,{kind='sweeping_slash',dx=-1,dy=0}));assert(C.owned(s,'spirit').id==e.id and e.position.x==5)
  local explored=P.encode(s.explored);for _=1,20 do G.preview(s,'sweeping_slash',1,1)end
  assert(explored==P.encode(s.explored))
  p.position.x,p.position.y=8,4;local aim=G.preview(s,'sweeping_slash',1,1);assert(not aim.valid)
 end)
 test('an enemy outside familiar reach rejects the command at zero cost',function()
  local s,p=trial();G.spawn_enemy(s,'core:enemy/mossbound_guard',8,6,100000)
  local before=G.snapshot(s);assert(not G.submit(s,{kind='sweeping_slash',dx=1,dy=0}));equal(before,G.snapshot(s))
  assert(G.submit(s,{kind='sweeping_slash',dx=-1,dy=0}));before=G.snapshot(s)
  assert(not G.submit(s,{kind='sweeping_slash',dx=1,dy=0}));equal(before,G.snapshot(s))
 end)
 test('a spirit command uses one ordinary proc pipeline and placement manufactures no attacks or Echo',function()
  local s,p=trial();G.set_boon_stacks(s,p.id,'core:boon/temporal_echo','common',1)
  local _,_,events=G.submit(s,{kind='sweeping_slash',dx=1,dy=0})
  for _,v in ipairs(events)do assert(v.kind~='AttackPerformed' and v.kind~='AbilityUsed')end
  assert(not next(s.delayed_effects))
  local e=G.spawn_enemy(s,'core:enemy/mossbound_guard',10,6,100000)
  assert(G.submit(s,{kind='sweeping_slash',dx=1,dy=0}));assert(e.hp<10)
 end)
 test('owned familiar and next commanded attack roundtrip exactly and reject forged ownership',function()
  local s,p=trial();assert(G.submit(s,{kind='sweeping_slash',dx=1,dy=0}))
  G.spawn_enemy(s,'core:enemy/mossbound_guard',10,6,100000)
  local snap=G.snapshot(s);local b=G.restore(P.decode(P.encode(snap)))
  local _,_,a=G.submit(s,{kind='sweeping_slash',dx=1,dy=0});local _,_,c=G.submit(b,{kind='sweeping_slash',dx=1,dy=0})
  equal(a,c);equal(G.snapshot(s),G.snapshot(b))
  for _,e in ipairs(snap.entities)do if e.controller==C.controller then e.owner_id=9999 end end
  assert(not pcall(G.restore,snap))
 end)
end
