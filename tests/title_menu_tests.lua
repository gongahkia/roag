local Game=require('src.game')
local Title=require('src.title_menu')

return function(test,equal)
    test('title defaults to Continue only for a resumable active run',function()
        assert(Title.default_selection({status='absent'})==2)
        assert(Title.default_selection({status='terminal'})==2)
        assert(Title.default_selection({status='recovered'})==1)
        assert(Title.resumable({status='active'}))
        assert(not Title.resumable({status='incompatible'}))
    end)
    test('title save summary describes real saved state without modifying it',function()
        local state=Game.new_stage(13,{class_id='core:actor/ranger'})
        local before=Game.snapshot(state)
        local heading,detail=Title.save_summary({status='active',state=state})
        assert(heading:find('Ranger',1,true) and heading:find('Lv 1',1,true))
        assert(detail:find('Overgrown Ruins',1,true) and
            detail:find('HP 20/20',1,true))
        equal(before,Game.snapshot(state))
        assert(Title.save_summary({status='terminal'})=='RUN COMPLETE')
        assert(Title.save_summary({status='pending_terminal'})==
            'UNLOCK RECOVERY NEEDED')
        assert(Title.save_summary({status='incompatible'})=='INCOMPATIBLE SAVE')
        assert(Title.save_summary({status='corrupt'})=='DAMAGED SAVE')
    end)
end
