#!/usr/bin/env python3
"""Compile reviewed room prototypes to plain Lua definitions for the game."""

import argparse
import json
from pathlib import Path

from room_data import room_data


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/room_expansion.lua"
FIELDS = ("id", "roles", "rows", "sockets", "markers", "editable", "structures")


def lua(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, list):
        return "{" + ",".join(lua(item) for item in value) + "}"
    if isinstance(value, dict):
        return "{" + ",".join(f"[{lua(key)}]={lua(item)}"
                              for key, item in value.items()) + "}"
    raise TypeError(value)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='verify compiled definitions without writing')
    args = parser.parse_args()
    proposals = room_data()["proposals"]["families"]
    order = ["core:room/" + group["family"] for group in proposals]
    definitions = {}
    for group in proposals:
        for variant in group["variants"]:
            definition = {key: variant[key] for key in FIELDS}
            definition["rotations"] = [0, 1, 2, 3]
            definition["mirror"] = True
            definition["protected_default"] = True
            definitions[variant["id"]] = definition
    assert len(order) == 15 and len(definitions) == 105
    lines = ["-- Generated by tools/write_room_expansion.py from reviewed room prototypes.",
             "-- Plain data only; no Python dependency at game runtime.",
             "local Expansion={}",
             "Expansion.order=" + lua(order),
             "Expansion.definitions={"]
    for room_id, definition in definitions.items():
        lines.append("    [" + lua(room_id) + "]=" + lua(definition) + ",")
    lines.extend(("}", "return Expansion", ""))
    compiled = "\n".join(lines)
    if args.check:
        assert OUTPUT.read_text() == compiled, 'Stale room definitions; run make room-expansion'
        print(f"PASS {len(definitions)} compiled rooms match live authored data")
    else:
        OUTPUT.write_text(compiled)
        print(f"Wrote {len(definitions)} approved rooms to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
